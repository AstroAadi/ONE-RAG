# ─────────────────────────────────────────────────────────────────────────────
# Pydantic models
# ─────────────────────────────────────────────────────────────────────────────

class PaginationMeta(BaseModel):
    page:        int
    page_size:   int
    total_items: int
    total_pages: int
    has_next:    bool
    has_prev:    bool
    next_page:   Optional[int] = None
    prev_page:   Optional[int] = None


class Author(BaseModel):
    name:        str
    nationality: str
    birth_year:  int


class Publisher(BaseModel):
    name:    str
    country: str


class Book(BaseModel):
    book_id:       str
    title:         str
    isbn:          str
    genre:         str
    language:      str
    pages:         int
    published_year: int
    rating:        float
    available:     bool
    author:        Author
    publisher:     Publisher
    tags:          List[str]
    inventory:     Dict[str, Any] = Field(default_factory=dict)
    edition_details: Dict[str, Any] = Field(default_factory=dict)
    reader_engagement: Dict[str, Any] = Field(default_factory=dict)


class PaginatedBooks(BaseModel):
    data:       List[Book]
    pagination: PaginationMeta
    filters:    Dict[str, Any] = Field(default_factory=dict)



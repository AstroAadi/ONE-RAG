def get_current_user(
    creds: HTTPBasicCredentials = Security(_basic),
) -> Dict:
    user = _USERS.get(creds.username)
    if not user or not secrets.compare_digest(creds.password, user["password"]):
        raise HTTPException(
            status_code=401,
            detail="Invalid username or password",
            headers={"WWW-Authenticate": "Basic"},
        )
    return {"username": creds.username, "role": user["role"]}


def _build_pagination(page: int, page_size: int, total: int) -> PaginationMeta:
    total_pages = math.ceil(total / page_size) if total else 0
    return PaginationMeta(
        page=page,
        page_size=page_size,
        total_items=total,
        total_pages=total_pages,
        has_next=page < total_pages,
        has_prev=page > 1,
        next_page=page + 1 if page < total_pages else None,
        prev_page=page - 1 if page > 1 else None,
    )


def _paginate(items: List[Dict[str, Any]], page: int, page_size: int) -> List[Dict[str, Any]]:
    start = (page - 1) * page_size
    return items[start : start + page_size]


